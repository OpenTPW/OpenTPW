/// <summary>Modifier flags carried by one SDL keyboard transition.</summary>
[Flags]
public enum ModifierKeys { None = 0, Shift = 1, Control = 2, Alt = 4, Gui = 8 }
/// <summary>Pointer button names used by the game's input state.</summary>
public enum MouseButton { Left, Middle, Right, Button1, Button2, Button3, Button4, Button5 }
/// <summary>A keyboard transition, retaining repeat and modifier information.</summary>
public readonly record struct KeyEvent( Key Key, bool Down, ModifierKeys Modifiers, bool Repeat = false );
/// <summary>A pointer button transition within an input frame.</summary>
public readonly record struct MouseEvent( MouseButton MouseButton, bool Down );
/// <summary>Input-frame data consumed by the game, without a rendering-library dependency.</summary>
public interface InputSnapshot
{
	IReadOnlyList<KeyEvent> KeyEvents { get; }
	IReadOnlyList<MouseEvent> MouseEvents { get; }
	IReadOnlyList<char> KeyCharPresses { get; }
	System.Numerics.Vector2 MousePosition { get; }
	float WheelDelta { get; }
	bool IsMouseDown( MouseButton button );
}
